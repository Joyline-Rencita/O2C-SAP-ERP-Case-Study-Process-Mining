INSERT INTO _CEL_P2P_BSIK_ACTIVITIES_DELTA
SELECT *
FROM _CEL_P2P_BSIK_ACTIVITIES_DELTA AS NEW_ACTIVITIES
 WHERE NOT EXISTS (
                    SELECT 1 FROM _CEL_P2P_BSIK_ACTIVITIES_DELTA AS OLD_ACTIVITIES
                    WHERE NEW_ACTIVITIES._CASE_KEY=OLD_ACTIVITIES._CASE_KEY
                      AND NEW_ACTIVITIES.ACTIVITY_EN=OLD_ACTIVITIES.ACTIVITY_EN
                        AND NEW_ACTIVITIES._ACTIVITY_KEY=OLD_ACTIVITIES._ACTIVITY_KEY 
                           AND NEW_ACTIVITIES.EVENTTIME=OLD_ACTIVITIES.EVENTTIME
                     AND  NEW_ACTIVITIES.TRANSACTION_CODE <=> OLD_ACTIVITIES.TRANSACTION_CODE
                    );

