INSERT INTO P2P_CDHDR_CDPOS
	SELECT
	CHANGES.MANDANT
	,CHANGES.FNAME
	,CHANGES.TABNAME
	,CHANGES.TABKEY
	,CHANGES.VALUE_OLD
	,CHANGES.VALUE_NEW
	,CHANGES.EVENTTIME
	,CHANGES.CHANGENR
    ,CHANGES.CHNGIND
	,CHANGES.TCODE
	,CHANGES.OBJECTCLAS
	,CHANGES.OBJECTID
	,CHANGES.USERNAME
	FROM TMP_P2P_CDHDR_CDPOS AS CHANGES 
