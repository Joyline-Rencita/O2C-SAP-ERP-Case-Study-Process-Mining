DROP VIEW IF EXISTS P2P_LFM1;

CREATE VIEW P2P_LFM1 AS(
SELECT 
	LFM1.*,
    CAST(LFM1.ERDAT AS DATE) AS TS_ERDAT
   ,T052.ZDART
   ,T052.ZFAEL
   ,T052.ZMONA
   ,T052.ZTAG1
   ,T052.ZPRZ1
   ,T052.ZTAG2
   ,T052.ZPRZ2
   ,T052.ZTAG3
   ,LFM1.EPOCH
FROM 
    LFM1
LEFT JOIN T052 AS T052 ON 1=1
   AND LFM1.MANDT = T052.MANDT
   AND LFM1.ZTERM = T052.ZTERM
WHERE EXISTS(
    SELECT * 
    FROM P2P_EKKO_STAGING AS C 
    WHERE 1=1
    AND LFM1.MANDT = C.MANDT 
    AND LFM1.LIFNR = C.LIFNR
    AND LFM1.EKORG = C.EKORG)
);
