DROP VIEW IF EXISTS P2P_BSAK;

CREATE VIEW P2P_BSAK AS 
SELECT 
    BSAK.*,
    P2P_BSAK_STAGING.TS_AUGDT, 
    P2P_BSAK_STAGING.TS_AUGCP,
    P2P_BSAK_STAGING.EPOCH
FROM
    BSAK AS BSAK JOIN
    P2P_BSAK_STAGING ON 1=1
        AND BSAK.MANDT= P2P_BSAK_STAGING.MANDT
        AND BSAK.BUKRS= P2P_BSAK_STAGING.BUKRS
        AND BSAK.GJAHR= P2P_BSAK_STAGING.GJAHR
        AND BSAK.BELNR= P2P_BSAK_STAGING.BELNR
        AND BSAK.BUZEI= P2P_BSAK_STAGING.BUZEI
;

