DROP VIEW IF EXISTS P2P_BSIK;

CREATE VIEW P2P_BSIK AS 
SELECT 
    BSIK.*,
    P2P_BSIK_STAGING.TS_AUGDT, 
    P2P_BSIK_STAGING.TS_AUGCP,
    P2P_BSIK_STAGING.EPOCH
FROM 
    BSIK AS BSIK JOIN 
    P2P_BSIK_STAGING ON 1=1
        AND BSIK.MANDT= P2P_BSIK_STAGING.MANDT
        AND BSIK.BUKRS= P2P_BSIK_STAGING.BUKRS
        AND BSIK.GJAHR= P2P_BSIK_STAGING.GJAHR
        AND BSIK.BELNR= P2P_BSIK_STAGING.BELNR
        AND BSIK.BUZEI= P2P_BSIK_STAGING.BUZEI
;

