DROP VIEW IF EXISTS P2P_BSEG_UNION;

CREATE VIEW P2P_BSEG_UNION AS 
SELECT *, EPOCH FROM P2P_BSAK
UNION ALL 
SELECT *,EPOCH FROM P2P_BSIK;

DROP VIEW IF EXISTS P2P_BSEG;
 
CREATE VIEW P2P_BSEG AS(
SELECT *,EPOCH FROM (
SELECT
    BSEG.*,    ROW_NUMBER()
        OVER(PARTITION BY BSEG.MANDT, BSEG.BUKRS, BSEG.BELNR, BSEG.GJAHR, BSEG.BUZEI
            ORDER BY BSEG.MANDT, BSEG.BUKRS, BSEG.BELNR, BSEG.GJAHR, BSEG.BUZEI, _CELONIS_CHANGE_DATE DESC) AS NUM,EPOCH
FROM
    P2P_BSEG_UNION AS BSEG) NUMBERED_BSEG WHERE NUM=1
);

