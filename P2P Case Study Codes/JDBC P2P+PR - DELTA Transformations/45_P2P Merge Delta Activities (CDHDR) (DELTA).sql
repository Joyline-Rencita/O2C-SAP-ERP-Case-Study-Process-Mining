--Cleanup

DELETE FROM
    _CEL_P2P_CDHDR_ACTIVITIES_DELTA
WHERE
    EVENTTIME IS NULL;

DELETE FROM
    _CEL_P2P_CDHDR_ACTIVITIES_DELTA
WHERE
    ACTIVITY_EN IS NULL AND
    ACTIVITY_DE IS NULL;

DELETE FROM
    _CEL_P2P_CDHDR_ACTIVITIES_DELTA
WHERE
    YEAR(EVENTTIME) > 5000 
;

-- Statistics
SELECT ANALYZE_STATISTICS('_CEL_P2P_CDHDR_ACTIVITIES_DELTA');


-- Name Mapping
UPDATE _CEL_P2P_CDHDR_ACTIVITIES_DELTA AS ACT
SET CHANGED_TABLE_TEXT_EN = NM.PRETTY_NAME
FROM P2P_NAME_MAPPING_TABLES AS NM
WHERE 1=1
   AND ACT.CHANGED_TABLE = NM.TABLE_NAME
   AND NM."LANGUAGE" = 'E';

UPDATE _CEL_P2P_CDHDR_ACTIVITIES_DELTA AS ACT
SET CHANGED_TABLE_TEXT_DE = NM.PRETTY_NAME
FROM P2P_NAME_MAPPING_TABLES AS NM
WHERE 1=1
   AND ACT.CHANGED_TABLE = NM.TABLE_NAME
   AND NM."LANGUAGE" = 'D';


-- Merge
INSERT INTO _CEL_P2P_CDHDR_ACTIVITIES
SELECT *
FROM _CEL_P2P_CDHDR_ACTIVITIES_DELTA AS NEW_ACTIVITIES
 WHERE NOT EXISTS (
                    SELECT 1 FROM _CEL_P2P_CDHDR_ACTIVITIES AS OLD_ACTIVITIES
                    WHERE NEW_ACTIVITIES._CASE_KEY=OLD_ACTIVITIES._CASE_KEY
                      AND NEW_ACTIVITIES.ACTIVITY_EN=OLD_ACTIVITIES.ACTIVITY_EN
                        AND NEW_ACTIVITIES._ACTIVITY_KEY=OLD_ACTIVITIES._ACTIVITY_KEY 
                    );
